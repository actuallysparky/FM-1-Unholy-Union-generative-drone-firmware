"""Offline real-DSP Choir Master profiles. No network, instrument access or target compiler.
Run after native table generation: python3 tools/calibrate_choir.py --output build/choir
Then --header firmware/src/holy_mix_profiles.h exports the reviewed compact measurements.
"""
import argparse,concurrent.futures,hashlib,json,math,os,subprocess,statistics,shlex
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',type=Path,default=ROOT/'build/choir');p.add_argument('--header',type=Path);p.add_argument('--reuse',action='store_true');a=p.parse_args()
a.output.mkdir(parents=True,exist_ok=True)
cc=shlex.split(os.environ.get('CC','cc'))+['-O2','-w']
sdk=Path('/Library/Developer/CommandLineTools/SDKs/MacOSX26.5.sdk')
if sdk.exists():cc+=['-isysroot',str(sdk)]
probe=a.output/'probe';subprocess.run(cc+['-I'+str(ROOT/'build/gen'),'-I'+str(ROOT/'firmware/src'),'-I'+str(ROOT/'tests'),'-o',str(probe),str(ROOT/'tests/choir_probe.c'),'-lm'],cwd=ROOT,check=True)
notes=[36,48,60,72,84];profiles=a.output/'profiles.json'
if a.reuse:
 rows=json.loads(profiles.read_text())['measurements']
else:
 inventory=[tuple(map(int,x.split())) for x in subprocess.check_output([str(probe),'inventory'],text=True).splitlines()]
 jobs=[(f,p,m,n,v) for f,p in inventory for m in range(3) for n in notes for v in [64,96]]
 def measure(job):return json.loads(subprocess.check_output([str(probe),'profile',*map(str,job)],cwd=ROOT,text=True))
 with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:rows=list(pool.map(measure,jobs))
 profiles.write_text(json.dumps({'rate':44100,'window_ms':400,'metric':'maximum overlapping-400ms stereo-mean K-weighted energy; sample peak, not integrated LUFS/true peak','registers':notes,'velocities':[64,96],'measurements':rows},indent=2)+'\n')
 print('Measured',len(rows),'preset/register/role/velocity cases',flush=True)
# Profiles use the louder velocity for safe repeatable calibration; velocity remains a player's expression.
energy={};peak={};low={};high={}
for r in rows:
 key=(r['family'],r['preset'],r['mode'],r['note'])
 energy[key]=max(energy.get(key,-120),r['energy_db']);peak[key]=max(peak.get(key,-120),r['peak_db'])
 (low if r['velocity']==64 else high)[key]=r['energy_db']
assert len(energy)==len(rows)//2 and all(math.isfinite(x) for x in energy.values())
target=[round(statistics.median(v for (f,p,m,n),v in energy.items() if m==mode and n in [48,60,72])*2) for mode in range(3)]
summary={'profile_rows':len(energy),'table_bytes':7*16*3*5*3,'median_half_db':target,'energy_range_db':[min(energy.values()),max(energy.values())],'profile_sha256':hashlib.sha256(profiles.read_bytes()).hexdigest()}
(a.output/'summary.json').write_text(json.dumps(summary,indent=2)+'\n');print(json.dumps(summary),flush=True)
if a.header:
 def quant(v):return max(-120,min(126,round(v*2)))
 text='/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/calibrate_choir.py from real DSP; 44.1 kHz, K-weighted max 400 ms.\n * Half-dB energy and unclipped sample-peak profiles; not LUFS/true-peak certification.\n * Source profile SHA256: '+summary['profile_sha256']+' */\n'
 text+='static const int8_t HOLY_MIX_TARGET[3] = {'+','.join(map(str,target))+'};\n'
 for name,data in [('HOLY_MIX_ENERGY64',low),('HOLY_MIX_ENERGY96',high),('HOLY_MIX_PEAK',peak)]:
  text+='static const int8_t '+name+'[7][16][3][5] = {\n'
  for f in range(7):
   text+=' {\n'
   for p in range(16):
    text+='  {'+','.join('{'+','.join(str(max(-120,min(126,math.ceil(data.get((f,p,m,n),-60)*2))) if name=='HOLY_MIX_PEAK' else quant(data.get((f,p,m,n),-60))) for n in notes)+'}' for m in range(3))+'},\n'
   text+=' },\n'
  text+='};\n'
 a.header.write_text(text)
 print('Wrote',a.header)
